"""
Regenerate replay tests' expected CSVs after a DELIBERATE output change, proving only the intended columns changed
(Mickey's rule: replays stay byte-identical; a deliberate change is regenerated by replay with a checker).

    python scripts/regenerate_expected.py tests/test_reference_runs.py tests/test_kim2019_replay.py ... \\
        --allow-columns set_independent_variable set_independent_value

Each test file's test functions are run in this process with the pipeline's CSV writers watched. When an assertion
fails, the last CSV the test read from runs/ (an expected file) is compared with the matching CSV the replay just
wrote (same kind: dataset or observations): with the allowed columns removed (dataset CSV: those columns;
observations CSV: rows about those columns) they must be IDENTICAL. Only then is the expected file overwritten, and
the test run again (a test may compare several files). Anything else stops with the difference. Back up runs/
first (scripts/backup_runs.py).
"""
from __future__ import annotations

import argparse
import csv
import importlib.util
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests"))
sys.path.insert(0, str(ROOT / "src"))
RUNS = ROOT / "runs"


def _rows(text: str):
    return list(csv.reader(io.StringIO(text)))


def without(text: str, allowed: set, observations: bool):
    rows = _rows(text)
    if not rows:
        return rows
    head = rows[0]
    if observations:
        col = head.index("column")
        return [head] + [r for r in rows[1:] if r[col] not in allowed]
    keep = [i for i, c in enumerate(head) if c not in allowed]
    return [[r[i] if i < len(r) else "" for i in keep] for r in rows]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--allow-columns", nargs="+", required=True)
    ap.add_argument("tests", nargs="+", type=Path)
    args = ap.parse_args()
    allowed = set(args.allow_columns)

    reads, writes = [], []
    real_read = Path.read_text

    def read_text(self, *a, **k):
        p = Path(self).resolve()
        if p.suffix == ".csv" and RUNS in p.parents:
            reads.append(p)
        return real_read(self, *a, **k)

    Path.read_text = read_text
    from parameter_extractor.ingestion import flatten_to_template as ft, observations as ob
    real_csv, real_obs = ft.write_template_csv, ob.write_observations_csv

    def write_csv(records, out_path, *a, **k):
        real_csv(records, out_path, *a, **k)
        writes.append(("data", Path(out_path).read_text()))      # kept now: tests write into temporary folders
    write_csv.__dict__ = real_csv.__dict__
    ft.write_template_csv = write_csv

    def write_obs(obs, out_path, *a, **k):
        real_obs(obs, out_path, *a, **k)
        writes.append(("obs", Path(out_path).read_text()))
    ob.write_observations_csv = write_obs
    import parameter_extractor.pipeline as pl
    for mod_ in (pl,):
        if hasattr(mod_, "write_template_csv"):
            mod_.write_template_csv = write_csv
        if hasattr(mod_, "write_observations_csv"):
            mod_.write_observations_csv = write_obs

    for test in args.tests:
        spec = importlib.util.spec_from_file_location(test.stem, test)
        mod = importlib.util.module_from_spec(spec)
        sys.path.insert(0, str(test.parent))
        spec.loader.exec_module(mod)
        for name, fn in list(vars(mod).items()):
            if not (name.startswith("test_") and callable(fn)):
                continue
            for attempt in range(30):
                reads.clear(), writes.clear()
                try:
                    fn()
                    print(f"PASS {test.name}::{name}" + (f" (after {attempt} update(s))" if attempt else ""))
                    break
                except AssertionError:
                    if not reads or not writes:
                        print(f"  (not regenerated: expected files read {[str(r) for r in reads]}, CSVs written "
                              f"{len(writes)})")
                        raise
                    expected = reads[-1]
                    kind = "obs" if "observations" in expected.name else "data"
                    produced = [t for k, t in writes if k == kind]
                    if not produced:
                        raise
                    new, old = produced[-1], expected
                    a = without(real_read(old), allowed, kind == "obs")
                    b = without(new, allowed, kind == "obs")
                    if a != b:
                        diff = [(i, x, y) for i, (x, y) in enumerate(zip(a, b)) if x != y][:3]
                        sys.exit(f"STOP {test.name}::{name}: {old.relative_to(ROOT)} differs beyond the allowed "
                                 f"columns (rows {len(a)} vs {len(b)}); first differences: {diff}")
                    old.write_text(new)
                    print(f"  updated {old.relative_to(ROOT)} (only {', '.join(sorted(allowed))} changed)")
            else:
                sys.exit(f"STOP {test.name}::{name}: still failing after 30 updates")


if __name__ == "__main__":
    main()
