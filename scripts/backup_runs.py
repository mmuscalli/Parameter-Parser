"""
Back up runs/ (P2, 2026-11-11): the reference runs and fixtures the test suite replays, the local-model runs, the
handoff answers. runs/ is never pushed (its audits hold the papers' text), so this archive is its only copy outside
the working tree. Run it after recording or regenerating a reference, and before any change that regenerates one.

    python scripts/backup_runs.py                  # ../Backups/runs_backup_<YYYYmmdd-HHMMSS>.tar.gz
    python scripts/backup_runs.py --skip-images    # without page_images/, figures/, tables/, equations/ crops
    python scripts/backup_runs.py --list           # the archives made so far

The archive is read back after writing (every file listed, the count compared) and never overwrites an older one;
old archives are never deleted here. Restore with: tar -xzf ../Backups/runs_backup_<stamp>.tar.gz (from the
repository root; it unpacks into runs/).
"""
import argparse
import sys
import tarfile
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "runs"
BACKUPS = ROOT.parent / "Backups"
IMAGE_DIRS = {"page_images", "figures", "tables", "equations"}
SKIP = {"__pycache__", ".DS_Store"}


def files_to_archive(skip_images: bool):
    for path in sorted(RUNS.rglob("*")):
        rel = path.relative_to(ROOT)
        parts = set(rel.parts)
        if parts & SKIP or (skip_images and parts & IMAGE_DIRS):
            continue
        if path.is_file() or (path.is_dir() and not any(path.iterdir())):     # empty folders too: an exact restore
            yield path, rel


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--skip-images", action="store_true", help="leave out image crops (regenerated by a replay)")
    ap.add_argument("--dest", type=Path, default=BACKUPS, help=f"folder for the archive (default {BACKUPS})")
    ap.add_argument("--list", action="store_true", help="list the archives already made and exit")
    a = ap.parse_args()
    if a.list:
        for p in sorted(a.dest.glob("runs_backup_*.tar.gz")):
            print(f"{p.stat().st_size / 1e6:8.1f} MB  {p.name}")
        return 0
    if not RUNS.is_dir():
        print(f"no runs/ folder at {RUNS}")
        return 1
    a.dest.mkdir(parents=True, exist_ok=True)
    target = a.dest / f"runs_backup_{datetime.now():%Y%m%d-%H%M%S}{'_no-images' if a.skip_images else ''}.tar.gz"
    if target.exists():
        print(f"{target} already exists")
        return 1
    files = list(files_to_archive(a.skip_images))
    size = sum(p.stat().st_size for p, _ in files if p.is_file())
    partial = target.with_suffix(".partial")
    with tarfile.open(partial, "w:gz") as tar:
        for path, rel in files:
            tar.add(path, arcname=str(rel), recursive=False)
    with tarfile.open(partial, "r:gz") as tar:              # read back: every member, and the count
        stored = tar.getmembers()
    if len(stored) != len(files):
        print(f"archive check failed: {len(stored)} files stored, {len(files)} expected; left as {partial}")
        return 1
    partial.rename(target)
    print(f"{sum(p.is_file() for p, _ in files):,} files ({size / 1e6:.1f} MB) -> {target} ({target.stat().st_size / 1e6:.1f} MB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
